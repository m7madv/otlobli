export function handle(request: Request) {
  const url = new URL(request.url);
  const pathname = url.pathname.replace(/\/+$/, "");
  const isInvitation = pathname.endsWith("/join");
  const slug = pathname.endsWith("/privacy")
    ? "privacy"
    : pathname.endsWith("/terms")
    ? "terms"
    : "home";
  return new Response(
    render(isInvitation ? invitationPage(url) : pages[slug]),
    {
      headers: {
        "content-type": "text/html; charset=utf-8",
        "cache-control": isInvitation ? "no-store" : "public, max-age=300",
        "x-content-type-options": "nosniff",
        "referrer-policy": "no-referrer",
        "content-security-policy":
          "default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
      },
    },
  );
}

